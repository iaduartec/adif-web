import { activeTheoryConceptRegistry } from "../content/theory-concepts";
import { listOriginalPracticeQuestions } from "../lib/content/original-practice-repository";

const questions = listOriginalPracticeQuestions({ status: "reviewed" });
if (questions.some((question) => !/^orig-[a-z0-9-]+$/.test(question.id))) {
  throw new Error("Reviewed original practice IDs must use the stable orig- ID namespace.");
}
for (const question of questions) {
  if (question.conceptIds.length === 0 || question.conceptIds.some((id) => !activeTheoryConceptRegistry.has(id))) {
    throw new Error(`Original question ${question.id} has no active persisted learning concept.`);
  }
}

const rows = questions.map((question) => ({
  id: question.id,
  answer: question.answer,
  concepts: question.conceptIds,
  bucket: `practice:original:${question.domain}`,
}));
const conceptIds = [...new Set(questions.flatMap((question) => question.conceptIds))].sort();
const json = JSON.stringify(rows).replaceAll("'", "''");
const conceptJson = JSON.stringify(conceptIds).replaceAll("'", "''");
const ids = questions.map((question) => `'${question.id.replaceAll("'", "''")}'`).join(",\n  ");

process.stdout.write(`-- Generated by scripts/export-original-practice-registry.ts. Do not hand-edit the registry payload.
-- Private answer keys remain server-only; origin/domain stay in the reviewed Git datasets.
insert into private.learning_concepts (concept_id, active)
select concept.concept_id, true
from jsonb_array_elements_text('${conceptJson}'::jsonb) as concept(concept_id)
on conflict (concept_id) do nothing;

update private.learning_questions
set active = false
where simulation_id like 'practice:original:%'
  and question_id <> all(array[
  ${ids}
]::text[]);

insert into private.learning_questions (question_id, correct_answer, concept_ids, simulation_id, active)
select row.id, row.answer, row.concepts, row.bucket,
  not exists (
    select 1
    from unnest(row.concepts) as mapped(concept_id)
    left join private.learning_concepts concept
      on concept.concept_id = mapped.concept_id and concept.active
    where concept.concept_id is null
  )
from jsonb_to_recordset('${json}'::jsonb)
  as row(id text, answer text, concepts text[], bucket text)
on conflict (question_id) do update
set correct_answer = excluded.correct_answer,
    concept_ids = excluded.concept_ids,
    simulation_id = excluded.simulation_id,
    active = private.learning_questions.active and excluded.active;

create or replace function private.enforce_original_practice_simulation_mode()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  if new.mode = 'simulation' and new.question_id like 'orig-%' then
    raise exception 'Original practice questions cannot be submitted in simulation mode.' using errcode = '23514';
  end if;
  return new;
end;
$$;
revoke all on function private.enforce_original_practice_simulation_mode() from public, anon, authenticated;

drop trigger if exists question_attempts_original_practice_mode on public.question_attempts;
create trigger question_attempts_original_practice_mode
before insert on public.question_attempts
for each row execute function private.enforce_original_practice_simulation_mode();
`);
